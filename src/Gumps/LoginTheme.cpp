bool IsUrl(const astr_t &value)
{
    return value.rfind("crossuo://", 0) == 0 || value.rfind("http://", 0) == 0 ||
           value.rfind("https://", 0) == 0;
}

astr_t UrlToHttp(const astr_t &url)
{
    if (url.rfind("crossuo://", 0) != 0)
    {
        return url;
    }
    return "https://" + url.substr(strlen("crossuo://"));
}

// Fetches a url into memory (theme text and theme images alike). No cache
// file is involved: the web build has no guaranteed writable tree at boot, and
// a re-fetch per boot matches the remote-config contract anyway.
bool FetchToMemory(const astr_t &url, std::vector<uint8_t> &out, size_t cap)
{
    // a deployment-relative path ("/stream/<encoded url>", the web shell's
    // proxy lane) is a same-origin request, not an absolute url: the XHR
    // transport resolves it against the page origin
    const auto http = IsUrl(url) ? UrlToHttp(url) : url;
    http_init();
    http_response response;
    for (const auto &candidate :
         { http,
           (http.rfind("https://", 0) == 0) ? "http://" + http.substr(strlen("https://")) : http })
    {
        if (http_get(candidate.c_str(), nullptr, cap, &response) && response.status == 200 &&
            !response.body.empty())
        {
            out = response.body;
            return true;
        }
    }
    Error(Client, "login theme: fetch failed for %s", url.c_str());
    return false;
}

// Local candidate resolution for an image: absolute path, theme-relative,
// data dir relative, then the plain file name in the working directory.
bool IsAbsolutePath(const astr_t &file)
{
    return !file.empty() && (file[0] == '/' || (file.size() > 1 && file[1] == ':'));
}

fs_path ResolveLocalImage(const astr_t &baseDir, const astr_t &file)
{
    if (file.empty())
    {
        return fs_path_from("");
    }
    if (IsAbsolutePath(file))
    {
        return fs_path_from(file);
    }

    std::vector<fs_path> candidates;
    if (!baseDir.empty())
    {
        candidates.push_back(fs_path_join(fs_path_from(baseDir), file));
    }
    candidates.push_back(fs_path_join(fs_path_from(fs_path_ascii(g_UOPath)), file));
    candidates.push_back(fs_path_from(file));
    for (const auto &candidate : candidates)
    {
        if (fs_path_exists(candidate))
        {
            return candidate;
        }
    }
    return fs_path_from("");
}

// split "a, b, c" into trimmed tokens
astr_t Lower(const astr_t &value)
{
    return str_lower(str_trim(value));
}

LOGIN_THEME_WIDGET_TYPE ParseWidgetType(const astr_t &value)
{
    static const struct
    {
        const char *name;
        LOGIN_THEME_WIDGET_TYPE type;
    } table[] = {
        { "image", LOGIN_THEME_WIDGET_TYPE::Image },
        { "gump", LOGIN_THEME_WIDGET_TYPE::Gump },
        { "gump_tiled", LOGIN_THEME_WIDGET_TYPE::GumpTiled },
        { "resizepic", LOGIN_THEME_WIDGET_TYPE::Resizepic },
        { "text", LOGIN_THEME_WIDGET_TYPE::Text },
        { "textbox", LOGIN_THEME_WIDGET_TYPE::TextBox },
        { "button", LOGIN_THEME_WIDGET_TYPE::Button },
        { "checkbox", LOGIN_THEME_WIDGET_TYPE::Checkbox },
        { "slider", LOGIN_THEME_WIDGET_TYPE::Slider },
        { "html_link", LOGIN_THEME_WIDGET_TYPE::HtmlLink },
    };
    const auto lower = Lower(value);
    for (const auto &entry : table)
    {
        if (lower == entry.name)
        {
            return entry.type;
        }
    }
    return LOGIN_THEME_WIDGET_TYPE::None;
}

LOGIN_THEME_BIND ParseBind(const astr_t &value)
{
    static const struct
    {
        const char *name;
        LOGIN_THEME_BIND bind;
    } table[] = {
        { "account", LOGIN_THEME_BIND::Account },
        { "password", LOGIN_THEME_BIND::Password },
        { "auto_login", LOGIN_THEME_BIND::AutoLogin },
        { "autologin", LOGIN_THEME_BIND::AutoLogin },
        { "save_password", LOGIN_THEME_BIND::SavePassword },
        { "savepassword", LOGIN_THEME_BIND::SavePassword },
        { "music", LOGIN_THEME_BIND::Music },
        { "music_volume", LOGIN_THEME_BIND::MusicVolume },
    };
    const auto lower = Lower(value);
    for (const auto &entry : table)
    {
        if (lower == entry.name)
        {
            return entry.bind;
        }
    }
    return LOGIN_THEME_BIND::None;
}

EXTERNAL_TEXTURE_DRAW_MODE ParseDrawMode(const astr_t &value)
{
    const auto lower = Lower(value);
    if (lower == "stretch" || lower == "scale")
    {
        return EXTERNAL_TEXTURE_DRAW_MODE::Stretch;
    }
    if (lower == "tile")
    {
        return EXTERNAL_TEXTURE_DRAW_MODE::Tile;
    }
    if (lower == "fit")
    {
        return EXTERNAL_TEXTURE_DRAW_MODE::Fit;
    }
    return EXTERNAL_TEXTURE_DRAW_MODE::Native;
}

// numbers accept decimal and 0x-prefixed hex (graphic ids/hues are hex in
// every UO reference, positions stay decimal)
int ParseInt(const astr_t &value, int fallback = 0)
{
    const auto text = str_trim(value);
    if (text.empty())
    {
        return fallback;
    }
    const bool hex = text.size() > 2 && text[0] == '0' && (text[1] == 'x' || text[1] == 'X');
    return (int)strtol(hex ? text.c_str() + 2 : text.c_str(), nullptr, hex ? 16 : 10);
}

// a color key value: a gump hue (decimal or 0x-prefixed RGB555, see
// ParseInt) or a web color "#RRGGBB" / "RRGGBB" converted to the hue layout.
// Web hex is what everyone reaches for first; the 16-bit form stays valid
// because shard references and color pickers speak it.
uint16_t ParseColor(const astr_t &value)
{
    const auto text = str_trim(value);
    if (text.empty())
    {
        return 0;
    }
    const bool web = text[0] == '#' ||
                     (text.size() == 6 &&
                      text.find_first_not_of("0123456789abcdefABCDEF") == astr_t::npos);
    if (web)
    {
        // web color: strtoul gives 0xRRGGBB, uo_color32_to_16 reads that
        // layout (R at bit 16)
        return (uint16_t)uo_color32_to_16(
            (int)strtoul(text.c_str() + (text[0] == '#' ? 1 : 0), nullptr, 16));
    }
    return (uint16_t)ParseInt(value);
}

// one `key = value` line into the widget being assembled
void ApplyWidgetKey(LoginThemeWidget &widget, const astr_t &key, const astr_t &value)
{
    const auto k = Lower(key);
    if (k == "id")
    {
        widget.Id = str_trim(value);
    }
    else if (k == "type")
    {
        widget.Type = ParseWidgetType(value);
    }
    else if (k == "bind")
    {
        widget.Bind = ParseBind(value);
        if (widget.Bind == LOGIN_THEME_BIND::None && !str_trim(value).empty())
        {
            Warning(Client, "login theme: unknown bind '%s'", value.c_str());
        }
    }
    else if (k == "action")
    {
        widget.Action = Lower(value);
    }
    else if (k == "x")
    {
        widget.X = ParseInt(value);
    }
    else if (k == "y")
    {
        widget.Y = ParseInt(value);
    }
    else if (k == "width" || k == "w")
    {
        widget.Width = ParseInt(value);
    }
    else if (k == "height" || k == "h")
    {
        widget.Height = ParseInt(value);
    }
    else if (k == "graphic")
    {
        widget.Graphic = (uint16_t)ParseInt(value);
    }
    else if (k == "graphic-selected")
    {
        widget.GraphicSelected = (uint16_t)ParseInt(value);
    }
    else if (k == "graphic-pressed")
    {
        widget.GraphicPressed = (uint16_t)ParseInt(value);
    }
    else if (k == "graphic-checked")
    {
        widget.GraphicChecked = (uint16_t)ParseInt(value);
    }
    else if (k == "graphic-disabled")
    {
        widget.GraphicDisabled = (uint16_t)ParseInt(value);
    }
    else if (k == "image")
    {
        widget.Image = str_trim(value);
    }
    else if (k == "text")
    {
        widget.Text = str_trim(value);
    }
    else if (k == "font")
    {
        widget.Font = ParseInt(value);
    }
    else if (k == "unicode")
    {
        widget.Unicode = str_to_bool(value);
    }
    else if (k == "color")
    {
        widget.Color = ParseColor(value);
    }
    else if (k == "color-selected")
    {
        widget.ColorSelected = (uint16_t)ParseInt(value);
    }
    else if (k == "color-focused")
    {
        widget.ColorFocused = (uint16_t)ParseInt(value);
    }
    else if (k == "max-length" || k == "maxlength")
    {
        widget.MaxLength = ParseInt(value);
    }
    else if (k == "masked")
    {
        widget.Masked = str_to_bool(value);
    }
    else if (k == "blink")
    {
        widget.Blink = str_to_bool(value);
    }
    else if (k == "text-position")
    {
        widget.TextPosition = str_lower(str_trim(value));
    }
    else if (k == "tooltip")
    {
        widget.Tooltip = str_trim(value);
    }
    else if (k == "min")
    {
        widget.MinValue = ParseInt(value);
    }
    else if (k == "max")
    {
        widget.MaxValue = ParseInt(value);
    }
    else if (k == "link-color")
    {
        widget.LinkColor = ParseColor(value);
    }
    else if (k == "url")
    {
        widget.Url = str_trim(value);
    }
    else
    {
        Warning(Client, "login theme: unknown widget key '%s'", key.c_str());
    }
}

// validate the widget once its block closes; returns false to drop it
bool FinishWidget(const LoginTheme::ImageMap &images, LoginThemeWidget &widget)
{
    if (widget.Type == LOGIN_THEME_WIDGET_TYPE::None)
    {
        Warning(Client, "login theme: widget '%s' has no type, dropped", widget.Id.c_str());
        return false;
    }
    if (widget.Type == LOGIN_THEME_WIDGET_TYPE::Image)
    {
        if (widget.Image.empty())
        {
            Warning(Client, "login theme: image widget '%s' has no image", widget.Id.c_str());
            return false;
        }
        if (images.find(widget.Image) == images.end())
        {
            Warning(
                Client,
                "login theme: widget '%s' references unknown image '%s'",
                widget.Id.c_str(),
                widget.Image.c_str());
            return false;
        }
    }
    if (widget.Type == LOGIN_THEME_WIDGET_TYPE::HtmlLink && widget.Url.empty())
    {
        Warning(Client, "login theme: html_link '%s' has no url, dropped", widget.Id.c_str());
        return false;
    }
    return true;
}

struct ThemeLine
{
    astr_t Section; // `[image]`-style prefix, empty for plain lines
    astr_t Key;
    astr_t Value;
    bool HasClose = false; // the line ended with a `}` (closes the block)
};

// Phase 1: image records and their attributes. Image blocks are flat (they
// precede the widget blocks), each one a set of keys after an [image] header;
// the next [image] header starts a new record. Returns the image map and
// consumes the lines up to the first widget block.
LoginTheme::ImageMap ParseImages(const std::vector<ThemeLine> &lines)
{
    LoginTheme::ImageMap images;
    LoginThemeImage *current = nullptr;
    astr_t pendingName;

    for (const auto &line : lines)
    {
        const auto k = Lower(line.Key);
        const bool inImageSection = Lower(line.Section) == "image";
        // image records may appear anywhere: outside an [image] section only
        // the explicit `image`/`name` headers are records, and their
        // attributes are the keys that follow until the next record. A
        // widget's own `image = <name>` is inside a widget block (`id`
        // opened) and is skipped here.
        if (!inImageSection && (k == "id" || k == "type"))
        {
            // a widget block starts: the image record (if any) is complete,
            // and a later `image = <name>` belongs to the widget, not to it
            current = nullptr;
            continue;
        }
        if (k == "name" && inImageSection && !line.Value.empty())
        {
            // `[image] name = background` opens the record
            current = &images[str_trim(line.Value)];
            continue;
        }
        if (k == "image")
        {
            // "[image]" header with a `name` on the same logical block, or
            // the compact form handled below
            if (!line.Value.empty())
            {
                current = &images[str_trim(line.Value)];
            }
            else
            {
                pendingName.clear();
                current = nullptr;
            }
            continue;
        }
        if (k == "name" && current == nullptr)
        {
            current = &images[str_trim(line.Value)];
            continue;
        }
        if (k == "file" && current != nullptr)
        {
            current->File = str_trim(line.Value);
        }
        else if (k == "mode" && current != nullptr)
        {
            current->Mode = ParseDrawMode(line.Value);
        }
        else if (k == "tiled" && current != nullptr)
        {
            current->Mode = str_to_bool(line.Value) ? EXTERNAL_TEXTURE_DRAW_MODE::Tile :
                                                      EXTERNAL_TEXTURE_DRAW_MODE::Native;
        }
        else if (k == "anchor-x" && current != nullptr)
        {
            current->X = ParseInt(line.Value);
        }
        else if (k == "anchor-y" && current != nullptr)
        {
            current->Y = ParseInt(line.Value);
        }
    }

    // drop image records that never got a file (they may be declared later;
    // the widget validation reports the dangling reference)
    for (auto it = images.begin(); it != images.end();)
    {
        if (it->second.File.empty())
        {
            it = images.erase(it);
        }
        else
        {
            ++it;
        }
    }
    return images;
}

// Phase 2: widget blocks. Every widget is a set of `key = value` lines opened
// by `id =` / `{` and closed by `}` (an `id` line also closes the previous
// widget for brace-less files). Returns the accepted widgets.
std::vector<LoginThemeWidget>
ParseWidgets(const std::vector<ThemeLine> &lines, const LoginTheme::ImageMap &images)
{
    std::vector<LoginThemeWidget> widgets;
    LoginThemeWidget current;
    bool inWidget = false;

    auto close = [&]()
    {
        if (!inWidget)
        {
            return;
        }
        inWidget = false;
        if (FinishWidget(images, current))
        {
            widgets.push_back(current);
        }
        current = LoginThemeWidget();
    };

    for (const auto &line : lines)
    {
        const auto k = Lower(line.Key);
        // image records are recognized by their [image]/name header; every
        // other key belongs to whichever block is open here
        if (k == "name" && Lower(line.Section) == "image")
        {
            continue;
        }
        if (!inWidget &&
            (k == "file" || k == "mode" || k == "tiled" || k == "anchor-x" || k == "anchor-y"))
        {
            continue; // image attributes before the first widget block
        }

        if (k == "id")
        {
            close();
            current.Id = str_trim(line.Value);
            inWidget = true;
            continue;
        }
        if (k == "type" && !inWidget)
        {
            // a bare `type =` without an id still starts a widget
            inWidget = true;
        }

        if (!inWidget && k != "type")
        {
            // stray theme-level keys (the [theme] header, version, ...) are
            // documented but currently unused
            continue;
        }
        if (!inWidget)
        {
            inWidget = true;
        }
        ApplyWidgetKey(current, line.Key, line.Value);
        if (line.HasClose)
        {
            close();
        }
    }
    close();
    return widgets;
}

// tokenizes the theme into key/value lines. The theme grammar is simpler
// than the client's config grammar, so it gets its own reader: one record per
// `key = value`, `#`/`;` comments, optional double quotes around the value,
// and `{`/`}` block delimiters. Brace handling is explicit here because the
// blocks are per-widget records (see ParseWidgets).
std::vector<ThemeLine> Tokenize(const std::vector<uint8_t> &data)
{
    std::vector<ThemeLine> lines;
    if (data.empty())
    {
        return lines;
    }
    const astr_t text((const char *)data.data(), data.size());

    size_t pos = 0;
    while (pos < text.size())
    {
        size_t eol = text.find('\n', pos);
        if (eol == astr_t::npos)
        {
            eol = text.size();
        }
        astr_t line = text.substr(pos, eol - pos);
        pos = eol + 1;
        if (!line.empty() && line.back() == '\r')
        {
            line.pop_back();
        }

        size_t first = line.find_first_not_of(" \t");
        if (first == astr_t::npos)
        {
            continue;
        }
        line = line.substr(first);
        if (line[0] == '#' || line[0] == ';')
        {
            continue;
        }

        // a leading [section] is a header for the whole line; the rest is
        // parsed as key/value records like any other line
        astr_t section;
        if (!line.empty() && line[0] == '[')
        {
            const auto close = line.find(']');
            if (close == astr_t::npos)
            {
                continue;
            }
            section = line.substr(1, close - 1);
            line = line.substr(close + 1);
            if (section.rfind("image", 0) == 0)
            {
                // `[image NAME]`: the record header itself is one line
                astr_t name = section.substr(strlen("image"));
                if (!name.empty() && (name[0] == ' ' || name[0] == '\t'))
                {
                    name.erase(0, 1);
                }
                ThemeLine header;
                header.Section = "image";
                header.Key = "name";
                header.Value = name;
                if (!header.Value.empty())
                {
                    lines.push_back(header);
                }
            }
            line = astr_t(" ") + line;
        }

        std::vector<astr_t> fragments;
        {
            astr_t current;
            bool quoted = false;
            for (const char c : line)
            {
                if (c == '"')
                {
                    quoted = !quoted;
                }
                if (c == ',' && !quoted)
                {
                    fragments.push_back(current);
                    current.clear();
                    continue;
                }
                current.push_back(c);
            }
            fragments.push_back(current);
        }

        auto trim = [](astr_t &str)
        {
            const auto b = str.find_first_not_of(" \t");
            if (b == astr_t::npos)
            {
                str.clear();
                return;
            }
            const auto e = str.find_last_not_of(" \t");
            str = str.substr(b, e - b + 1);
        };

        for (auto &fragment : fragments)
        {
            ThemeLine out;
            out.Section = section;

            const auto eq = fragment.find('=');
            astr_t key = eq == astr_t::npos ? fragment : fragment.substr(0, eq);
            astr_t value = eq == astr_t::npos ? astr_t() : fragment.substr(eq + 1);
            trim(key);
            trim(value);

            // block delimiters may sit on either side of the key or trail the
            // value: `{ id = x`, `{ type = gump }`, `x = 0 }`
            while (!key.empty() && (key.front() == '{' || key.front() == '}'))
            {
                out.HasClose = out.HasClose || key.front() == '}';
                key.erase(0, 1);
                trim(key);
            }
            while (!key.empty() && (key.back() == '{' || key.back() == '}'))
            {
                out.HasClose = out.HasClose || key.back() == '}';
                key.pop_back();
            }
            trim(key);
            while (!value.empty() && (value.front() == '{' || value.front() == '}'))
            {
                out.HasClose = out.HasClose || value.front() == '}';
                value.erase(0, 1);
                trim(value);
            }
            while (!value.empty() && (value.back() == '{' || value.back() == '}'))
            {
                out.HasClose = out.HasClose || value.back() == '}';
                value.pop_back();
            }
            trim(value);
            if (value.size() >= 2 && value.front() == '"' && value.back() == '"')
            {
                value = value.substr(1, value.size() - 2);
            }

            if (key.empty())
            {
                continue;
            }
            out.Key = key;
            out.Value = value;
            lines.push_back(out);
        }
    }
    return lines;
}

bool ParseTheme(const std::vector<uint8_t> &data, LoginTheme &theme)
{
    const auto lines = Tokenize(data);
    theme.Images = ParseImages(lines);
    theme.Widgets = ParseWidgets(lines, theme.Images);
    return !theme.Widgets.empty();
}

