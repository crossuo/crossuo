static fs_path file_path(const fs_path &path, const char *str, va_list arg)
{
    char out[FS_MAX_PATH] = { 0 };
    vsnprintf(out, sizeof(out) - 1, str, arg);
    return fs_insensitive(fs_path_join(path, out));
}

// To use with any data generated by the client itself
// eg. .xuo files, .cfg files.
