{
    UopAnimationFrame frame;
    frame.DataStart = Ptr;
    frame.GroupId = ReadInt16LE();
    frame.FrameId = ReadInt16LE();
    frame.Unk1 = ReadUInt32LE();
    frame.Unk2 = ReadUInt32LE();
    frame.PixelDataOffset = ReadUInt32LE();
    return frame;
}

std::vector<UopAnimationFrame> CFileManager::UopReadAnimationFramesData()
{
    auto header = UopReadAnimationHeader();
    std::vector<UopAnimationFrame> data;
    data.reserve(header.FrameCount);
    for (uint32_t i = 0; i < header.FrameCount; i++)
    {
        data.emplace_back(UopReadAnimationFrame());
    }
    return data;
}

void CFileManager::UopReadAnimationFrameInfo(
    AnimationFrameInfo &result,
    AnimationDirection &direction,
    const UopFileEntry *block,
    bool isCorpse)
{
    if (block == nullptr || block->Hash == 0)
    {
        return;
    }

    std::vector<uint8_t> scratchBuffer;
    size_t scratchSize = block->DecompressedSize;
    if (block->Flags == 3)
    {
        if (!UopDecompressBlockBwt(block, scratchBuffer, direction.FileIndex))
        {
            return;
        }
        scratchSize = scratchBuffer.size();
    }
    else
    {
        scratchBuffer.reserve(block->DecompressedSize);
        if (!UopDecompressBlock(block, scratchBuffer.data(), direction.FileIndex))
        {
            return;
        }
    }
    // FIXME: CFileManager SHOULD not be a DataReader! In fact, no class need to be. Clean up!
    SetData(scratchBuffer.data(), scratchSize);
    const auto _header = UopReadAnimationHeader();
    (void)_header;
    auto frame = UopReadAnimationFrame(); // read only first frame to get image dimensions
    Ptr = frame.DataStart + frame.PixelDataOffset + PALETTE_SIZE;
    // corrupt/truncated block hardening: validate before dereferencing (a
    // garbage offset used to trap the heap here)
    if (
        frame.DataStart == nullptr || frame.DataStart < scratchBuffer.data() ||
        Ptr + sizeof(AnimationFrameInfo) > scratchBuffer.data() + scratchSize)
    {
        return;
    }
    auto frameInfo = (AnimationFrameInfo *)Ptr;
    result = *frameInfo;
    Move(sizeof(AnimationFrameInfo));
}

inline bool
CFileManager::UopReadAnimationFrames(const AnimationState &anim, LoadPixelData16Cb pLoadFunc)
{
    const auto block = uo_animation_group_get(anim);
    if (block == nullptr || block->Hash == 0)
    {
        return false;
    }

    std::vector<uint8_t> scratchBuffer;
    assert(anim.Group < MAX_ANIMATION_GROUPS_COUNT);
    auto &direction = g_Index.m_Anim[anim.Graphic].Groups[anim.Group].Direction[anim.Direction];
    size_t scratchSize = block->DecompressedSize;
    if (block->Flags == 3)
    {
        if (!UopDecompressBlockBwt(block, scratchBuffer, direction.FileIndex))
        {
            return false;
        }
        scratchSize = scratchBuffer.size();
    }
    else
    {
        scratchBuffer.reserve(block->DecompressedSize);
        if (!UopDecompressBlock(block, scratchBuffer.data(), direction.FileIndex))
        {
            return false;
        }
    }
    SetData(scratchBuffer.data(), scratchSize);

    const auto framesData = UopReadAnimationFramesData();

    // packs list frames as sequential FrameIds that may skip slots (sparse
    // frame ids); synthesize empty entries for the gaps so the per-direction
    // split below stays aligned with what the standard client computes
    std::vector<UopAnimationFrame> ordered;
    ordered.reserve(framesData.size() + 16);
    int lastFrameId = 1;
    for (const auto &fd : framesData)
    {
        while (int(fd.FrameId) - lastFrameId > 1)
        {
            lastFrameId += 1;
            UopAnimationFrame gap; // null DataStart == empty frame
            gap.FrameId = uint16_t(lastFrameId);
            ordered.push_back(gap);
        }
        ordered.push_back(fd);
        lastFrameId = fd.FrameId;
    }

    const int maxFrameCount = int(ordered.size());
    const int type = g_Index.m_Anim[anim.Graphic].Type;
    int frameCount = (maxFrameCount + MAX_MOBILE_DIRECTIONS / 2) / MAX_MOBILE_DIRECTIONS;
    if (type == AGT_EQUIPMENT)
    {
        // equipment animations always expose at least 10 frames
        frameCount = std::max(10, frameCount);
    }
    frameCount = std::max(1, std::min(frameCount, 0xFF));
    direction.FrameCount = uint8_t(frameCount);

    if (uo_animation_get(anim) != nullptr)
    {
        return true;
    }
    auto animation = uo_animation_create(anim);

    // corrupt/truncated block hardening: every frame offset below comes from
    // the (possibly garbage) block bytes - a bad offset used to walk the
    // palette/frame-header reads out of the scratch buffer and trap the whole
    // wasm heap ("memory access out of bounds") instead of degrading to a
    // missing frame
    const uint8_t *scratchBegin = scratchBuffer.data();
    const uint8_t *scratchEnd = scratchBegin + scratchSize;
    for (const auto &frameData : ordered)
    {
        const int frameDirection = (int(frameData.FrameId) - 1) / frameCount;
        if (frameDirection < anim.Direction)
        {
            continue;
        }
        if (frameDirection > anim.Direction)
        {
            break;
        }
        const int i = (int(frameData.FrameId) - 1) % frameCount;
        if (frameData.DataStart == nullptr)
        {
            continue;
        }
        if (frameData.DataStart < scratchBegin ||
            frameData.DataStart + frameData.PixelDataOffset + PALETTE_SIZE +
                    sizeof(AnimationFrameInfo) >
                scratchEnd)
        {
            Error(
                Data,
                "animation frame out of bounds (graphic %d group %d dir %d frame %d)",
                anim.Graphic,
                anim.Group,
                anim.Direction,
                i);
            continue;
        }

        Ptr = frameData.DataStart + frameData.PixelDataOffset;
        auto palette = (uint16_t *)Ptr;
        Move(PALETTE_SIZE);

        auto &frame = animation->Frames[i];
        LoadAnimationFrame(frame, palette, pLoadFunc);
    }
    return true;
}

void CFileManager::MulReadAnimationFrameInfo(
    AnimationFrameInfo &result, AnimationDirection &direction, uint8_t frameIndex, bool isCorpse)
{
    auto ptr = (uint8_t *)direction.Address;
    if (!direction.IsVerdata)
    {
        ptr = MulReadAnimationData(direction);
        if (ptr == nullptr || direction.Size < PALETTE_SIZE + sizeof(uint32_t))
        {
            return;
        }
    }
    SetData(ptr, direction.Size);

    Move(PALETTE_SIZE);
    uint8_t *dataStart = Ptr;
    int frameCount = ReadUInt32LE();
    if (frameCount > 0 && frameIndex >= frameCount)
    {
        frameIndex = 0;
    }

    if (frameIndex < frameCount)
    {
        uint32_t *frameOffset = (uint32_t *)Ptr;
        Ptr = dataStart + frameOffset[frameIndex];
        // corrupt index hardening: validate before dereferencing (a garbage
        // offset used to read outside the mapped data)
        if (Ptr == nullptr || Ptr + sizeof(AnimationFrameInfo) > End)
        {
            return;
        }
        auto frameInfo = (AnimationFrameInfo *)Ptr;
        result = *frameInfo;
    }
}

inline bool
CFileManager::MulReadAnimationFrames(const AnimationState &anim, LoadPixelData16Cb pLoadFunc)
{
    assert(anim.Group < MAX_ANIMATION_GROUPS_COUNT);
    auto &direction = g_Index.m_Anim[anim.Graphic].Groups[anim.Group].Direction[anim.Direction];
    auto ptr = (uint8_t *)direction.Address;
    if (!direction.IsVerdata)
    {
        ptr = MulReadAnimationData(direction);
        if (ptr == nullptr || direction.Size < PALETTE_SIZE + sizeof(uint32_t))
        {
            return false;
        }
    }
    SetData(ptr, direction.Size);

    uint16_t *palette = (uint16_t *)Start;
    Move(PALETTE_SIZE);

    uint8_t *dataStart = Ptr;
    uint32_t frameCount = ReadUInt32LE();
    // the count and its offset table come from the file: bound both against
    // the block data before indexing them, and clamp the stored per-direction
    // count to what the frame array can hold
    const size_t maxFrameCount = size_t(End - dataStart - 4) / sizeof(uint32_t);
    if (frameCount > maxFrameCount)
    {
        frameCount = uint32_t(maxFrameCount);
    }
    frameCount = std::min<uint32_t>(frameCount, 0xFF);
    uint32_t *frameOffset = (uint32_t *)Ptr;
    Ptr += frameCount * sizeof(uint32_t);
    //uint16_t color = g_Index.m_Anim[graphic].Color;

    direction.FrameCount = uint8_t(frameCount);
    if (uo_animation_get(anim) != nullptr)
    {
        return true;
    }
    auto animation = uo_animation_create(anim);

    for (uint32_t i = 0; i < frameCount; i++)
    {
        auto &frame = animation->Frames[i];
        if (frame.UserData != nullptr)
        {
            continue;
        }
        Ptr = dataStart + frameOffset[i];
        LoadAnimationFrame(frame, palette, pLoadFunc);
    }

    return true;
}

void CFileManager::LoadAnimationFrame(
    AnimationFrame &frame, uint16_t *palette, LoadPixelData16Cb pLoadFunc)
{
    // central bounds guard: callers hand out pointers computed from data that
    // can be garbage on the web streaming paths (an unlanded index block
    // yields a bogus direction.Address/Size); without this check the frame
    // header read below walks off the mapped data and traps the whole wasm
    // heap ("memory access out of bounds"), killing the client
    if (Ptr == nullptr || Ptr + sizeof(AnimationFrameInfo) > End)
    {
        Error(Data, "animation frame data out of bounds");
        return;
    }
    auto frameInfo = (AnimationFrameInfo *)Ptr;
    Move(sizeof(AnimationFrameInfo));

    frame.CenterX = frameInfo->CenterX;
    frame.CenterY = frameInfo->CenterY;
    if (frameInfo->Width == 0 || frameInfo->Height == 0)
    {
        Error(Data, "image data invalid (%d,%d)", frameInfo->Width, frameInfo->Height);
        return;
    }
    // corrupt/short data hardening: garbage dimensions (negative or absurd)
    // used to drive `pixels[block++]` far out of the pixel buffer below and
    // corrupt the heap / trap the wasm memory - degrade to a missing frame
    // instead. Legitimate UO animation frames are far smaller than this cap.
    if (
        frameInfo->Width < 0 || frameInfo->Height < 0 || frameInfo->Width > 1024 ||
        frameInfo->Height > 1024)
    {
        Error(Data, "image data out of range (%d,%d)", frameInfo->Width, frameInfo->Height);
        return;
    }

    const auto imageWidth = frameInfo->Width;
    const auto imageHeight = frameInfo->Height;
    const auto imageCenterX = frameInfo->CenterX;
    const auto imageCenterY = frameInfo->CenterY;
    const int textureSize = imageWidth * imageHeight;
    std::vector<uint16_t> pixels(textureSize, 0);
    if (pixels.size() != textureSize)
    {
        Error(Data, "couldn't allocate pixel data (%d bytes)", textureSize);
        return;
    }

    uint32_t header = ReadUInt32LE();
    while (header != 0x7FFF7FFF && !IsEOF())
    {
        const uint16_t runLength = (header & 0x0FFF);
        int x = (header >> 22) & 0x03FF;
        if ((x & 0x0200) != 0)
        {
            x |= 0xFFFFFE00;
        }

        int y = (header >> 12) & 0x03FF;
        if ((y & 0x0200) != 0)
        {
            y |= 0xFFFFFE00;
        }

        x += imageCenterX;
        y += imageCenterY + imageHeight;
        int block = (y * imageWidth) + x;
        for (int k = 0; k < runLength; k++)
        {
            const uint8_t paletteIndex = ReadUInt8();
            uint16_t val = palette[paletteIndex];
            if (val != 0)
            {
                val |= 0x8000;
            }
            // per-pixel bounds: a corrupt header/offset used to write out of
            // the pixel buffer (heap corruption / wasm trap)
            if (block >= 0 && block < textureSize)
            {
                pixels[block] = val;
            }
            block++;
        }
        header = ReadUInt32LE();
    }

    assert(pLoadFunc);
    assert(frame.UserData == nullptr);
    frame.UserData = pLoadFunc(imageWidth, imageHeight, pixels.data());
    if (frame.UserData != nullptr)
    {
    }
}

void CFileManager::LoadAnimationFrameInfo(
    AnimationFrameInfo &result, const AnimationState &anim, uint8_t frameIndex, bool isCorpse)
{
    assert(anim.Group < MAX_ANIMATION_GROUPS_COUNT);
    auto &direction = g_Index.m_Anim[anim.Graphic].Groups[anim.Group].Direction[0];
#if defined(XUO_EMSC)
    // web: source availability routing (see LoadAnimation). Legacy bodies
    // decode from the streamed anim.mul; the UOP AnimationFrame fallback
    // covers bodies the legacy set never carried (no anim.idx entry).
    if (direction.Size != 0)
    {
        MulReadAnimationFrameInfo(result, direction, frameIndex, isCorpse);
        if (result.Width != 0 || result.Height != 0)
        {
            return;
        }
    }
    UopReadAnimationFrameInfo(result, direction, uo_animation_group_get(anim), isCorpse);
#else
    if (direction.Size != 0)
    {
        MulReadAnimationFrameInfo(result, direction, frameIndex, isCorpse);
    }
    else
    {
        auto file = uo_animation_group_get(anim);
        UopReadAnimationFrameInfo(result, direction, file, isCorpse);
    }
#endif
}

bool CFileManager::LoadAnimation(const AnimationState &anim, LoadPixelData16Cb pLoadFunc)
{
    assert(anim.Group < MAX_ANIMATION_GROUPS_COUNT);
    auto &direction = g_Index.m_Anim[anim.Graphic].Groups[anim.Group].Direction[anim.Direction];
    bool res = false;
    if (direction.Size != 0)
    {
        res = MulReadAnimationFrames(anim, pLoadFunc);
    }
    else
    {
        res = UopReadAnimationFrames(anim, pLoadFunc);
    }
    return res;
}

ANIMATION_GROUPS_TYPE uo_type_by_graphic(uint16_t graphic)
{
    return graphic < 200 ? AGT_MONSTER : (graphic < 400 ? AGT_ANIMAL : AGT_HUMAN);
}

uint32_t uo_get_group_offset(ANIMATION_GROUPS group, uint16_t graphic)
{
    switch (group)
    {
        case AG_LOW:
        {
            return ((graphic - 200) * 65 + 22000) * sizeof(AnimIdxBlock);
        }
        break;

        case AG_HIGH:
        {
            return graphic * 110 * sizeof(AnimIdxBlock);
        }
        break;

        case AG_PEOPLE:
        {
            return ((graphic - 400) * 175 + 35000) * sizeof(AnimIdxBlock);
        }
        break;

        case AG_NONE:
        case AG_INVALID:
        default:
        {
            assert(false && "Invalid group parameter");
        }
    }
    return -1;
}

static bool uo_anim_group_is_die(ANIMATION_GROUPS_TYPE type, uint8_t group)
{
    switch (type)
    {
        case AGT_MONSTER:
        case AGT_SEA_MONSTER:
        {
            return (group == HAG_DIE_1 || group == HAG_DIE_2);
        }
        case AGT_HUMAN:
        case AGT_EQUIPMENT:
        {
            return (group == PAG_DIE_1 || group == PAG_DIE_2);
        }
        case AGT_ANIMAL:
        {
            return (group == LAG_DIE_1 || group == LAG_DIE_2);
        }
        default:
            break;
    }
    return false;
}

